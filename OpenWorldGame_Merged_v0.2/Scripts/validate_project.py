#!/usr/bin/env python3
"""Static integrity checks for the OWG Unreal source starter.

This does not replace UnrealHeaderTool, UnrealBuildTool, Editor, APK packaging,
or real-device gameplay/performance tests.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ERRORS: list[str] = []
WARNINGS: list[str] = []


def require(condition: bool, message: str) -> None:
    if not condition:
        ERRORS.append(message)


def main() -> int:
    project_file = ROOT / "OpenWorldGame.uproject"
    require(project_file.is_file(), "Missing OpenWorldGame.uproject")
    if project_file.is_file():
        try:
            project = json.loads(project_file.read_text(encoding="utf-8"))
        except Exception as exc:  # pragma: no cover - error path
            ERRORS.append(f"Invalid .uproject JSON: {exc}")
            project = {}
    else:
        project = {}

    modules = project.get("Modules", [])
    runtime_modules = [m for m in modules if m.get("Type") == "Runtime"]
    require(len(runtime_modules) == 1, "Expected exactly one Runtime module")
    module_name = runtime_modules[0].get("Name") if runtime_modules else "OpenWorldGame"
    module_dir = ROOT / "Source" / str(module_name)
    require((module_dir / f"{module_name}.Build.cs").is_file(), "Missing module Build.cs")
    require((ROOT / "Source" / f"{module_name}.Target.cs").is_file(), "Missing Game Target.cs")
    require((ROOT / "Source" / f"{module_name}Editor.Target.cs").is_file(), "Missing Editor Target.cs")

    source_files = list((ROOT / "Source").rglob("*.cpp")) + list((ROOT / "Source").rglob("*.h"))
    require(len(source_files) >= 12, "Expected C++ implementation and public headers")
    for path in source_files:
        text = path.read_text(encoding="utf-8")
        require(bool(text.strip()), f"Empty source file: {path.relative_to(ROOT)}")
        for include in re.findall(r'^\s*#include\s+"([^"]+)"', text, flags=re.MULTILINE):
            if include.endswith(".generated.h"):
                # Generated by UnrealHeaderTool; absence in source checkout is expected.
                continue
            if include.startswith("OWG"):
                possible = [path.parent / include, ROOT / "Source" / module_name / "Public" / include,
                            ROOT / "Source" / module_name / "Private" / include]
                require(any(candidate.is_file() for candidate in possible),
                        f"Unresolved project include {include} in {path.relative_to(ROOT)}")

    engine_ini = ROOT / "Config" / "DefaultEngine.ini"
    input_ini = ROOT / "Config" / "DefaultInput.ini"
    build_cs = module_dir / f"{module_name}.Build.cs"
    for required in (engine_ini, input_ini, build_cs):
        require(required.is_file(), f"Missing required config/build file: {required.relative_to(ROOT)}")

    if engine_ini.is_file():
        cfg = engine_ini.read_text(encoding="utf-8")
        require("/Script/OpenWorldGame.OWGGameMode" in cfg, "Default GameMode path not configured")
        require("/Script/OpenWorldGame.OWGGameInstance" in cfg, "Default GameInstance path not configured")
        require("com.abdullahlazim.openworldgame" in cfg, "Android package id missing")

    if input_ini.is_file():
        cfg = input_ini.read_text(encoding="utf-8")
        cpp = "\n".join(p.read_text(encoding="utf-8") for p in source_files if p.suffix == ".cpp")
        axis_names = set(re.findall(r'BindAxis\(TEXT\("([^"]+)"\)', cpp))
        action_names = set(re.findall(r'BindAction\(TEXT\("([^"]+)"\)', cpp))
        for name in sorted(axis_names):
            require(f'AxisName="{name}"' in cfg, f"Axis mapping missing for {name}")
        for name in sorted(action_names):
            require(f'ActionName="{name}"' in cfg, f"Action mapping missing for {name}")

    widget_h = ROOT / "Source" / module_name / "Public" / "OWGMainMenuWidget.h"
    widget_cpp = ROOT / "Source" / module_name / "Private" / "OWGMainMenuWidget.cpp"
    if widget_h.is_file() and widget_cpp.is_file():
        h = widget_h.read_text(encoding="utf-8")
        cpp = widget_cpp.read_text(encoding="utf-8")
        callbacks = re.findall(r' UFUNCTION\(\)\s*void\s+(Handle\w+)\s*\(', h)
        for callback in callbacks:
            require(f"UOWGMainMenuWidget::{callback}()" in cpp,
                    f"Widget callback declared but not implemented: {callback}")

    expected_docs = [
        "Docs/MASTER_SPEC_AR_v0.3.txt",
        "Docs/START_HERE_AR.md",
        "Docs/IMPLEMENTATION_STATUS_AR.md",
        "Docs/FILE_AND_DEPENDENCY_AUDIT.md",
        "Docs/ASSET_GAPS_AR.md",
        "Docs/TEST_MATRIX_AR.csv",
        "Docs/BUILD_REPORT.md",
        "Docs/TEST_REPORT.md",
        "Docs/ANDROID_DEVICE_TEST_MATRIX.csv",
        "Docs/ASSET_LICENSE_MANIFEST.csv",
    ]
    for relative in expected_docs:
        require((ROOT / relative).is_file(), f"Missing delivery document: {relative}")

    portable_core = [
        ROOT / "Source" / module_name / "Core" / "OWCredits.h",
        ROOT / "Source" / module_name / "Core" / "OWUnits.h",
        ROOT / "Source" / module_name / "Core" / "OWFrameStats.h",
        ROOT / "Source" / module_name / "Core" / "OWVehicleEntry.h",
        ROOT / "Source" / module_name / "SaveSystem" / "OWSaveData.h",
        ROOT / "Tests" / "HostTests" / "test_main.cpp",
        ROOT / "Scripts" / "run_host_tests.sh",
    ]
    for path in portable_core:
        require(path.is_file() and path.stat().st_size > 0,
                f"Missing merged core/test file: {path.relative_to(ROOT)}")

    generated_assets = list((ROOT / "Content").rglob("*.uasset")) + list((ROOT / "Content").rglob("*.umap"))
    if not generated_assets:
        WARNINGS.append("No .uasset/.umap art or map files are included; the greybox environment is spawned by C++ at runtime.")

    if ERRORS:
        print("STATIC INTEGRITY: FAIL")
        for item in ERRORS:
            print(f"ERROR: {item}")
    else:
        print("STATIC INTEGRITY: PASS")
        print(f"Project: {project_file.name}")
        print(f"Module: {module_name}")
        print(f"C++ source/header files checked: {len(source_files)}")
        print("Project includes, module files, default classes, Android config and input mappings: checked")

    for item in WARNINGS:
        print(f"WARNING: {item}")
    print("ENGINE COMPILE: NOT RUN (Unreal Engine 5.8 is not installed in this environment)")
    print("ANDROID APK: NOT BUILT (Android packaging toolchain/device is not available here)")
    return 1 if ERRORS else 0


if __name__ == "__main__":
    sys.exit(main())
